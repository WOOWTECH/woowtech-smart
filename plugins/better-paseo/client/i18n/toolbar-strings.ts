/** A button's English label as the reader's chosen language shows it; an unknown label stays English. */
export function toolbarLabel(
  label: string,
  preference: SettingsLanguagePreference,
  locale?: string | null,
): string {
  const language = resolveLanguage(preference, locale);
  if (language === "en") return label;
  // The checklist's status button names its task: "Set Run the tests status".
  const status = /^Set (.+) status$/.exec(label);
  if (status)
    return language === "zh-TW" ? `設定「${status[1]}」的狀態` : `设置“${status[1]}”的状态`;
  const latestCount = /^Back to latest\s*[\u00B7,]\s*(\d+) new lines?$/.exec(label);
  if (latestCount)
    return language === "zh-TW"
      ? `回到最新 · ${latestCount[1]} 行新輸出`
      : `回到最新 · ${latestCount[1]} 行新输出`;
  // "1 new line", "5 new lines"; the pill's template is "{count} new lines" (`backToLatestText`).
  const newLines = /^(\d+) new lines?$/.exec(label);
  if (newLines) return language === "zh-TW" ? `${newLines[1]} 行新輸出` : `${newLines[1]} 行新输出`;
  // A thought's sections: "1 step", "4 steps".
  const steps = /^(\d+) steps?$/.exec(label);
  if (steps) return `${steps[1]} 步`;
  const tokens = /^from (\d+(?:\.\d+)?[KM]?) tokens$/.exec(label);
  if (tokens)
    return language === "zh-TW" ? `壓縮前 ${tokens[1]} tokens` : `压缩前 ${tokens[1]} tokens`;
  const wakeup = /^Wake up in (\d+(?:s|m|h)(?: \d+m)?)$/.exec(label);
  if (wakeup) return language === "zh-TW" ? `${wakeup[1]} 後喚醒` : `${wakeup[1]} 后唤醒`;
  const labels = language === "zh-TW" ? ZH_TW : ZH;
  return labels[label] ?? label;
}

/**
 * The toast for a copy, from its button's label: "Copy path" says "Copied
 * path" (已复制路径). A menu entry's "2. " prefix is dropped; a label that
 * names nothing says "Copied".
 */
export function copiedToast(
  label: string,
  preference: SettingsLanguagePreference,
  locale?: string | null,
): string {
  const base = label.replace(/^\d+\.\s*/, "");
  if (resolveLanguage(preference, locale) === "zh-TW") {
    if (base.startsWith("Copy model name: "))
      return `已複製模型名稱：${base.slice("Copy model name: ".length)}`;
    const translated = ZH_TW[base];
    return translated?.startsWith("複製") ? `已${translated}` : "已複製";
  }
  if (base.startsWith("Copy model name: ")) {
    const name = base.slice("Copy model name: ".length);
    return resolveLanguage(preference, locale) === "zh-TW"
      ? `已複製模型名稱：${name}`
      : resolveLanguage(preference, locale) === "zh"
        ? `已复制模型名称：${name}`
        : `Copied model name: ${name}`;
  }
  if (resolveLanguage(preference, locale) === "zh") {
    const zh = ZH[base];
    return zh?.startsWith("复制") ? `已${zh}` : "已复制";
  }
  const match = /^Copy (.+)$/.exec(base);
  return match ? `Copied ${match[1]}` : "Copied";
}
