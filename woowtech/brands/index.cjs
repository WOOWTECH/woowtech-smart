// The brands this repository builds: woowtech smart and Apporo smart, one JSON file each in
// this folder, with the same fields. The brand a checkout builds is the one
// packages/protocol/src/brand-values.ts was generated for (woowtech/tools/apply-brand.mjs).
// TypeScript reads that file; app.config.js, the desktop app's packaging config and scripts,
// and the guards read the brand's JSON through this module. One switch for both means a build
// can't mix one brand's app with the other's daemon. The repository keeps woowtech's values.
const fs = require("node:fs");
const path = require("node:path");

const REPO_ROOT = path.resolve(__dirname, "../..");
const BRAND_VALUES_PATH = path.join(REPO_ROOT, "packages/protocol/src/brand-values.ts");
const BRAND_ID_LINE = /^export const BRAND_ID = "([a-z][a-z0-9-]*)";$/m;
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Every brand with a JSON file here, sorted. */
function brandIds() {
  return fs
    .readdirSync(__dirname)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -".json".length))
    .sort();
}

/** The brand's values from `<id>.json`. */
function loadBrand(id) {
  const file = path.join(__dirname, `${id}.json`);
  if (!fs.existsSync(file)) {
    throw new Error(`There is no brand "${id}": ${file} does not exist`);
  }
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

/** The id of the brand packages/protocol/src/brand-values.ts was generated for. */
function appliedBrandId() {
  const match = BRAND_ID_LINE.exec(fs.readFileSync(BRAND_VALUES_PATH, "utf8"));
  if (!match) {
    throw new Error(
      `${BRAND_VALUES_PATH} has no BRAND_ID line; regenerate it with woowtech/tools/apply-brand.mjs`,
    );
  }
  return match[1];
}

/** The values of the brand this checkout builds. */
function appliedBrand() {
  return loadBrand(appliedBrandId());
}

function renderValue(value, indent) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    const inner = `${indent}  `;
    const properties = Object.entries(value).map(([key, child]) => {
      const name = IDENTIFIER.test(key) ? key : JSON.stringify(key);
      return `${inner}${name}: ${renderValue(child, inner)},`;
    });
    return `{\n${properties.join("\n")}\n${indent}}`;
  }
  throw new Error(`A brand value must be a string, number, boolean or object: ${value}`);
}

/** packages/protocol/src/brand-values.ts for `brand`, before formatting. */
function renderBrandValues(brand) {
  return [
    `// Generated by woowtech/tools/apply-brand.mjs from woowtech/brands/${brand.id}.json. Change`,
    "// the JSON and run the tool instead of editing this file. The repository keeps woowtech's",
    "// values; a release tree for another brand applies that brand before it builds.",
    `export const BRAND_ID = ${JSON.stringify(brand.id)};`,
    "",
    `export const BRAND = ${renderValue(brand, "")} as const;`,
    "",
  ].join("\n");
}

module.exports = {
  BRAND_VALUES_PATH,
  REPO_ROOT,
  appliedBrand,
  appliedBrandId,
  brandIds,
  loadBrand,
  renderBrandValues,
};
